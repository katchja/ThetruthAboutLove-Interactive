import { initializeApp } from 'firebase/app';
import {
  getAuth,
  GoogleAuthProvider,
  signInWithPopup,
  signOut,
  User,
} from 'firebase/auth';
import {
  getFirestore,
  doc,
  getDocFromServer,
} from 'firebase/firestore';
import firebaseConfig from '../firebase-applet-config.json';

export const AUTHOR_EMAIL = 'butnaru.catalina@gmail.com';

const app = initializeApp(firebaseConfig);
export const db = getFirestore(app, firebaseConfig.firestoreDatabaseId);
export const auth = getAuth(app);

export enum OperationType {
  CREATE = 'create',
  UPDATE = 'update',
  DELETE = 'delete',
  LIST = 'list',
  GET = 'get',
  WRITE = 'write',
}

export interface FirestoreErrorInfo {
  error: string;
  operationType: OperationType;
  path: string | null;
  authInfo: {
    userId?: string | null;
    email?: string | null;
    emailVerified?: boolean | null;
    isAnonymous?: boolean | null;
    tenantId?: string | null;
    providerInfo?: {
      providerId?: string | null;
      email?: string | null;
    }[];
  };
}

export function handleFirestoreError(
  error: unknown,
  operationType: OperationType,
  path: string | null
): never {
  const errInfo: FirestoreErrorInfo = {
    error: error instanceof Error ? error.message : String(error),
    authInfo: {
      userId: auth.currentUser?.uid,
      email: auth.currentUser?.email,
      emailVerified: auth.currentUser?.emailVerified,
      isAnonymous: auth.currentUser?.isAnonymous,
      tenantId: auth.currentUser?.tenantId,
      providerInfo:
        auth.currentUser?.providerData?.map((provider) => ({
          providerId: provider.providerId,
          email: provider.email,
        })) || [],
    },
    operationType,
    path,
  };
  console.error('Firestore Error: ', JSON.stringify(errInfo));
  throw new Error(JSON.stringify(errInfo));
}

let connectionValidated = false;

export async function testFirestoreConnection(): Promise<void> {
  if (connectionValidated) return;
  connectionValidated = true;
  try {
    await getDocFromServer(doc(db, 'archive_config', 'book_metadata'));
  } catch (error) {
    if (
      error instanceof Error &&
      error.message.includes('the client is offline')
    ) {
      console.error('Please check your Firebase configuration.');
    }
  }
}

export function isVerifiedAuthorUser(user: User | null | undefined): boolean {
  if (!user) return false;
  return (
    Boolean(user.emailVerified) &&
    typeof user.email === 'string' &&
    user.email.toLowerCase() === AUTHOR_EMAIL.toLowerCase()
  );
}

export async function signInStudioAuthor(): Promise<User> {
  const provider = new GoogleAuthProvider();
  provider.setCustomParameters({
    login_hint: AUTHOR_EMAIL,
    prompt: 'select_account',
  });
  const result = await signInWithPopup(auth, provider);
  return result.user;
}

export async function signOutStudioAuthor(): Promise<void> {
  await signOut(auth);
}
